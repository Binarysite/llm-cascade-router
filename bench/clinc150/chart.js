#!/usr/bin/env node
// Draw the CLINC150 trade-off curve from the committed reports as an SVG:
// x = wrong fixed answers per 1,000 turns, y = share of answerable messages
// answered right without the LLM. One line per configuration, one point per
// threshold of the sweep; the threshold chosen on validation is ringed.
//   node bench/clinc150/chart.js [--check]
import { readFile, writeFile } from 'node:fs/promises';

/** @param {string} f */
const read = async (f) => JSON.parse(await readFile(new URL(`../../reports/${f}`, import.meta.url), 'utf8'));
const local = await read('clinc150.json');
const model = await read('clinc150-deepseek.json');
const OUT = new URL('../../reports/clinc150-tradeoff.svg', import.meta.url);
const X_MAX = 20;

const series = [
  { name: 'layers 1-2', points: local.sweepOnTest.layers12, key: 'minScore', chosen: local.selection.layers12.minScore,
    light: '#2a78d6', dark: '#3987e5', shape: 'circle' },
  { name: 'TF-IDF alone', points: local.sweepOnTest.tfidf, key: 'minConfidence',
    chosen: local.selection.tfidf.minConfidence,
    light: '#eb6834', dark: '#d95926', shape: 'square' },
  { name: 'cascade + TF-IDF', points: local.sweepOnTest.cascadeTfidf, key: 'minConfidence',
    chosen: local.selection.cascadeTfidf.minConfidence, light: '#1baf7a', dark: '#199e70', shape: 'diamond' },
  { name: 'model alone*', points: model.sweep.modelAlone, key: 'minConfidence', chosen: model.minConfidence,
    light: '#eda100', dark: '#c98500', shape: 'triangle' },
  { name: 'cascade + model*', points: model.sweep.cascadeModel, key: 'minConfidence', chosen: model.minConfidence,
    light: '#e87ba4', dark: '#d55181', shape: 'circle' },
];

const W = 760;
const H = 440;
const m = { top: 56, right: 150, bottom: 64, left: 64 };
const pw = W - m.left - m.right;
const ph = H - m.top - m.bottom;
const yMax = Math.max(0.1, ...series.flatMap((s) => s.points.map((p) => p.coverageOfAnswerable)));
const Y_MAX = Math.ceil(yMax * 10) / 10;
const x = (/** @type {number} */ v) => m.left + (Math.min(v, X_MAX) / X_MAX) * pw;
const y = (/** @type {number} */ v) => m.top + ph - (v / Y_MAX) * ph;
const f = (/** @type {number} */ n) => n.toFixed(1);

/** @param {string} shape @param {number} cx @param {number} cy @param {number} r */
function marker(shape, cx, cy, r) {
  if (shape === 'square') {
    return `<rect x="${f(cx - r)}" y="${f(cy - r)}" width="${f(2 * r)}" height="${f(2 * r)}" rx="1"/>`;
  }
  if (shape === 'diamond') {
    const k = r * 1.3;
    return `<path d="M${f(cx)} ${f(cy - k)}L${f(cx + k)} ${f(cy)}L${f(cx)} ${f(cy + k)}L${f(cx - k)} ${f(cy)}Z"/>`;
  }
  if (shape === 'triangle') {
    return `<path d="M${f(cx)} ${f(cy - r * 1.3)}L${f(cx + r * 1.2)} ${f(cy + r)}L${f(cx - r * 1.2)} ${f(cy + r)}Z"/>`;
  }
  return `<circle cx="${f(cx)}" cy="${f(cy)}" r="${f(r)}"/>`;
}

const out = [];
out.push(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" role="img" `
  + 'aria-labelledby="t d" font-family="system-ui, -apple-system, Segoe UI, sans-serif">');
out.push('<title id="t">CLINC150 banking: fixed answers right versus wrong, per threshold</title>');
out.push('<desc id="d">Generated by bench/clinc150/chart.js from reports/clinc150.json and '
  + 'reports/clinc150-deepseek.json. The tables in the README carry the same numbers.</desc>');
const darkSeries = series.map((s, i) => `.s${i}{stroke:${s.dark};fill:${s.dark}}`).join('');
out.push('<style>');
out.push('.bg{fill:#fcfcfb}.ink{fill:#0b0b0b}.ink2{fill:#52514e}.grid{stroke:#e4e3df}.axis{stroke:#8a8984}');
series.forEach((s, i) => out.push(`.s${i}{stroke:${s.light};fill:${s.light}}`));
out.push('.ring{fill:none;stroke-width:2}.line{fill:none;stroke-width:2;stroke-linejoin:round}');
out.push('@media (prefers-color-scheme: dark){.bg{fill:#1a1a19}.ink{fill:#f0efec}.ink2{fill:#c3c2b7}'
  + `.grid{stroke:#33332f}.axis{stroke:#77766f}${darkSeries}}`);
out.push('</style>');
out.push(`<rect class="bg" width="${W}" height="${H}"/>`);
out.push(`<text class="ink" x="${m.left}" y="24" font-size="15" font-weight="600">`
  + 'CLINC150 banking: more fixed answers cost more wrong ones</text>');
out.push(`<text class="ink2" x="${m.left}" y="42" font-size="12">One point per threshold on the test split; `
  + 'rings: thresholds in use (chosen on validation; 0.8 default for the model). * 2,000-message sample.</text>');
for (let v = 0; v <= Y_MAX + 1e-9; v += 0.1) {
  out.push(`<line class="grid" x1="${m.left}" x2="${m.left + pw}" y1="${f(y(v))}" y2="${f(y(v))}"/>`);
  out.push(`<text class="ink2" x="${m.left - 8}" y="${f(y(v) + 4)}" font-size="11" text-anchor="end">`
    + `${Math.round(v * 100)}%</text>`);
}
for (let v = 0; v <= X_MAX; v += 5) {
  out.push(`<text class="ink2" x="${f(x(v))}" y="${m.top + ph + 18}" font-size="11" text-anchor="middle">${v}</text>`);
}
out.push(`<line class="axis" x1="${m.left}" x2="${m.left + pw}" y1="${m.top + ph}" y2="${m.top + ph}"/>`);
out.push(`<text class="ink2" x="${m.left + pw / 2}" y="${H - 18}" font-size="12" text-anchor="middle">`
  + `wrong fixed answers per 1,000 turns (points past ${X_MAX} are drawn at the edge)</text>`);
out.push(`<text class="ink2" transform="translate(16 ${m.top + ph / 2}) rotate(-90)" font-size="12" `
  + 'text-anchor="middle">answerable messages answered right, no LLM</text>');

const labels = [];
series.forEach((s, i) => {
  const pts = [...s.points].sort((a, b) => a.wrongPer1000Turns - b.wrongPer1000Turns
    || a.coverageOfAnswerable - b.coverageOfAnswerable);
  const d = pts.map((p, j) => `${j ? 'L' : 'M'}${f(x(p.wrongPer1000Turns))} ${f(y(p.coverageOfAnswerable))}`).join('');
  out.push(`<g class="s${i}">`);
  out.push(`<path class="line" d="${d}"/>`);
  for (const p of pts) out.push(marker(s.shape, x(p.wrongPer1000Turns), y(p.coverageOfAnswerable), 3.5));
  const c = s.points.find((p) => p[s.key] === s.chosen);
  if (c) {
    out.push(`<circle class="ring" cx="${f(x(c.wrongPer1000Turns))}" cy="${f(y(c.coverageOfAnswerable))}" r="8"/>`);
  }
  out.push('</g>');
  const last = pts.at(-1);
  labels.push({ i, name: s.name, y: y(last.coverageOfAnswerable), shape: s.shape });
});
// Legend on the right, in the order of the lines' end heights, with its marker beside each name.
labels.sort((a, b) => a.y - b.y);
let ly = m.top + 8;
for (const l of labels) {
  const yy = Math.max(ly, Math.min(l.y, m.top + ph));
  out.push(`<g class="s${l.i}">${marker(l.shape, m.left + pw + 22, yy - 4, 4)}</g>`);
  out.push(`<text class="ink" x="${m.left + pw + 32}" y="${f(yy)}" font-size="12">${l.name}</text>`);
  ly = yy + 18;
}
out.push('</svg>');
const svg = `${out.join('\n')}\n`;

if (process.argv.includes('--check')) {
  if (svg !== await readFile(OUT, 'utf8')) {
    console.error('reports/clinc150-tradeoff.svg differs from a fresh render: node bench/clinc150/chart.js');
    process.exit(1);
  }
  console.log('reports/clinc150-tradeoff.svg matches the reports');
} else {
  await writeFile(OUT, svg);
  console.log('wrote reports/clinc150-tradeoff.svg');
}
